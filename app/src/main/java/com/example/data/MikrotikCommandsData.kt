package com.example.data

enum class MikrotikModule(val titleBn: String, val titleEn: String) {
    PPPOE("PPPoE সার্ভার ও ক্লায়েন্ট", "PPPoE Server & Client"),
    HOTSPOT("হটস্পট সার্ভার", "Hotspot Server"),
    DHCP("ডিএইচসিপি সার্ভার", "DHCP Server & Pool"),
    NAT("NAT ও পোর্ট ফরওয়ার্ডিং", "NAT & Port Forwarding"),
    FIREWALL("ফায়ারওয়াল নিরাপত্তা ফিল্টার", "Firewall Filter Security"),
    QUEUE("কিউ ও ব্যান্ডউইথ কন্ট্রোল", "Queue & Bandwidth Limits")
}

data class MikrotikParam(
    val wanInterface: String = "ether1",
    val lanInterface: String = "bridge-LAN",
    val lanSubnet: String = "192.168.88.0/24",
    val gatewayIp: String = "192.168.88.1",
    val poolRange: String = "192.168.88.10-192.168.88.254",
    val dnsServers: String = "8.8.8.8,1.1.1.1",
    // PPPoE
    val pppoeUser: String = "bd_user01",
    val pppoePass: String = "isp@pass123",
    val isPppoeServer: Boolean = false,
    val pppoePool: String = "10.10.10.2-10.10.10.254",
    // Hotspot
    val hotspotDnsName: String = "wifi.login",
    val hotspotRateLimit: String = "5M/10M",
    // Port forward
    val forwardDstPort: String = "8000",
    val forwardToIp: String = "192.168.88.200",
    val forwardToPort: String = "8000",
    // Queue
    val targetIp: String = "192.168.88.50/32",
    val maxLimitUpload: String = "10M",
    val maxLimitDownload: String = "20M"
)

object MikrotikCommandGenerator {

    fun generate(module: MikrotikModule, p: MikrotikParam): String {
        return when (module) {
            MikrotikModule.PPPOE -> generatePppoe(p)
            MikrotikModule.HOTSPOT -> generateHotspot(p)
            MikrotikModule.DHCP -> generateDhcp(p)
            MikrotikModule.NAT -> generateNat(p)
            MikrotikModule.FIREWALL -> generateFirewall(p)
            MikrotikModule.QUEUE -> generateQueue(p)
        }
    }

    private fun generatePppoe(p: MikrotikParam): String {
        return if (!p.isPppoeServer) {
            """
            # ======================================================
            # RouterOS: PPPoE Client Dial-Out Configuration
            # Generated by Router Doctor BD (Kabir Molla)
            # ======================================================
            
            # 1. Add PPPoE Client on WAN Interface
            /interface pppoe-client add name="pppoe-out1" \
                interface="${p.wanInterface}" \
                user="${p.pppoeUser}" \
                password="${p.pppoePass}" \
                profile=default \
                add-default-route=yes \
                use-peer-dns=yes \
                disabled=no
            
            # 2. Add NAT Masquerade for PPPoE Out
            /ip firewall nat add chain=srcnat out-interface=pppoe-out1 action=masquerade comment="PPPoE WAN NAT"
            
            # 3. MSS Clamping for PPPoE (Prevents Webpage Stalling)
            /ip firewall mangle add chain=forward protocol=tcp tcp-flags=syn tcp-mss=1453-65535 \
                action=change-mss new-mss=1452 passthrough=yes comment="Clamp MSS to PMTU"
            """.trimIndent()
        } else {
            """
            # ======================================================
            # RouterOS: PPPoE Server Configuration (ISP / Sub-ISP)
            # Generated by Router Doctor BD (Kabir Molla)
            # ======================================================
            
            # 1. Create IP Pool for PPPoE Clients
            /ip pool add name="pool-pppoe" ranges=${p.pppoePool}
            
            # 2. Create PPPoE Profile
            /ppp profile add name="profile-pppoe-standard" \
                local-address=${p.gatewayIp} \
                remote-address=pool-pppoe \
                dns-server=${p.dnsServers} \
                only-one=yes
            
            # 3. Enable PPPoE Server on LAN
            /interface pppoe-server server add service-name="RouterDoctor-PPPoE" \
                interface="${p.lanInterface}" \
                default-profile=profile-pppoe-standard \
                authentication=pap,chap,mschap2 \
                one-session-per-host=yes \
                disabled=no
            
            # 4. Add Sample Secret / User
            /ppp secret add name="${p.pppoeUser}" password="${p.pppoePass}" \
                service=pppoe profile=profile-pppoe-standard comment="Broadband Client"
            """.trimIndent()
        }
    }

    private fun generateHotspot(p: MikrotikParam): String {
        return """
        # ======================================================
        # RouterOS: Hotspot Captive Portal Setup
        # Generated by Router Doctor BD (Kabir Molla)
        # ======================================================
        
        # 1. Create Hotspot IP Pool
        /ip pool add name="pool-hotspot" ranges=${p.poolRange}
        
        # 2. Add Hotspot User Profile with Bandwidth Limit
        /ip hotspot user profile add name="profile-standard" \
            rate-limit="${p.hotspotRateLimit}" \
            shared-users=1 \
            keepalive-timeout=2m \
            status-autorefresh=1m \
            transparent-proxy=no
        
        # 3. Create Hotspot Server Profile
        /ip hotspot profile add name="hsprof-doc" \
            hotspot-address=${p.gatewayIp} \
            dns-name="${p.hotspotDnsName}" \
            html-directory=hotspot \
            login-by=http-chap,cookie \
            http-cookie-lifetime=1d
        
        # 4. Bind Hotspot Server to Interface
        /ip hotspot add name="hotspot-bd" \
            interface="${p.lanInterface}" \
            address-pool=pool-hotspot \
            profile=hsprof-doc \
            disabled=no
        
        # 5. Create Sample User
        /ip hotspot user add name="guest" password="123" profile=profile-standard comment="Standard Guest User"
        """.trimIndent()
    }

    private fun generateDhcp(p: MikrotikParam): String {
        return """
        # ======================================================
        # RouterOS: DHCP Server & LAN IP Setup
        # Generated by Router Doctor BD (Kabir Molla)
        # ======================================================
        
        # 1. Assign IP Address to LAN Bridge
        /ip address add address=${p.gatewayIp}/24 interface="${p.lanInterface}" network=${p.lanSubnet.substringBefore("/")}.0
        
        # 2. Create DHCP Address Pool
        /ip pool add name="dhcp-pool-lan" ranges=${p.poolRange}
        
        # 3. Create DHCP Server
        /ip dhcp-server add name="dhcp-lan" interface="${p.lanInterface}" address-pool=dhcp-pool-lan lease-time=12h disabled=no
        
        # 4. Add DHCP Network Scope
        /ip dhcp-server network add address=${p.lanSubnet} \
            gateway=${p.gatewayIp} \
            dns-server=${p.dnsServers} \
            comment="LAN Office/Home Scope"
        
        # 5. DNS Server with Cache
        /ip dns set allow-remote-requests=yes servers=${p.dnsServers} cache-size=4096KiB
        """.trimIndent()
    }

    private fun generateNat(p: MikrotikParam): String {
        return """
        # ======================================================
        # RouterOS: NAT & Port Forwarding (CCTV / Server)
        # Generated by Router Doctor BD (Kabir Molla)
        # ======================================================
        
        # 1. Standard Internet Masquerade
        /ip firewall nat add chain=srcnat out-interface="${p.wanInterface}" action=masquerade comment="Masquerade WAN"
        
        # 2. Port Forwarding (DST-NAT) for CCTV NVR / Web Server
        /ip firewall nat add chain=dstnat in-interface="${p.wanInterface}" protocol=tcp \
            dst-port=${p.forwardDstPort} action=dst-nat \
            to-addresses=${p.forwardToIp} to-ports=${p.forwardToPort} \
            comment="Forward port ${p.forwardDstPort} to Internal Device"
        
        # 3. Hairpin NAT (Access internal server using Public IP from inside LAN)
        /ip firewall nat add chain=srcnat src-address=${p.lanSubnet} dst-address=${p.forwardToIp} \
            protocol=tcp dst-port=${p.forwardToPort} out-interface="${p.lanInterface}" \
            action=masquerade comment="Hairpin NAT Rule"
        """.trimIndent()
    }

    private fun generateFirewall(p: MikrotikParam): String {
        return """
        # ======================================================
        # RouterOS: Hardened Security Firewall Filter Rules
        # Generated by Router Doctor BD (Kabir Molla)
        # ======================================================
        
        # 1. FastTrack Established Connections (Drastically Lowers CPU Usage)
        /ip firewall filter add chain=forward action=fasttrack-connection connection-state=established,related comment="FastTrack"
        /ip firewall filter add chain=forward action=accept connection-state=established,related comment="Accept established,related"
        
        # 2. Drop Invalid Packets
        /ip firewall filter add chain=input action=drop connection-state=invalid comment="Drop Invalid Input"
        /ip firewall filter add chain=forward action=drop connection-state=invalid comment="Drop Invalid Forward"
        
        # 3. Protect Router: Allow Established Input
        /ip firewall filter add chain=input action=accept connection-state=established,related comment="Accept Established to Router"
        
        # 4. Allow LAN Access to Winbox & Web Admin
        /ip firewall filter add chain=input action=accept in-interface="${p.lanInterface}" comment="Allow LAN to Manage Router"
        
        # 5. BLOCK External DNS Queries from WAN (Crucial: Prevents DDoS Amplification)
        /ip firewall filter add chain=input action=drop in-interface="${p.wanInterface}" protocol=udp dst-port=53 comment="Drop WAN DNS UDP"
        /ip firewall filter add chain=input action=drop in-interface="${p.wanInterface}" protocol=tcp dst-port=53 comment="Drop WAN DNS TCP"
        
        # 6. Drop All Other WAN Traffic to Router
        /ip firewall filter add chain=input action=drop in-interface="${p.wanInterface}" comment="Drop All Other Input from WAN"
        """.trimIndent()
    }

    private fun generateQueue(p: MikrotikParam): String {
        return """
        # ======================================================
        # RouterOS: Queue Simple Bandwidth Control
        # Generated by Router Doctor BD (Kabir Molla)
        # ======================================================
        
        # 1. Dedicated Client Rate Limit
        /queue simple add name="User-Bandwidth-Limit" \
            target=${p.targetIp} \
            max-limit=${p.maxLimitUpload}/${p.maxLimitDownload} \
            burst-limit=0/0 burst-threshold=0/0 burst-time=0s/0s \
            priority=8/8 queue=default-small/default-small \
            comment="Bandwidth capping for specific IP"
        
        # 2. Entire Subnet Limit
        /queue simple add name="Subnet-Total-Limit" \
            target=${p.lanSubnet} \
            max-limit=50M/100M \
            comment="Total ISP Package Limiter"
        """.trimIndent()
    }
}
